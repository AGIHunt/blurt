"""Copies the web mascot (assets/mascot: <sheet>.webp strips + mascot.json) to the web package and writes its CSS.

    python3 assets/mascot/tools/build.py            # write all outputs
    python3 assets/mascot/tools/build.py --check    # exit 1 if a committed output is stale (tests run this)

These strips are the earlier 1A round chick, still used by the web overlays (Windows / Linux) and the Tauri app. The
mac app no longer uses them: its mascot is the brand's 4A chick drawn and moved in code (Icons/MascotArt.swift, from
assets/brand/chick.swift); porting that to the web is in TODO.md.

Outputs
  Web    web/packages/icons/mascot/   strips + mascot.json + mascot.css (one @keyframes per clip: steps(1) through the
         timeline, so a page needs no JS to play it; prefers-reduced-motion → the clip's still frame) — @blurt/icons/mascot
Standard library only.
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1]
REPO = SRC.parents[1]
WEB =REPO / "web/packages/icons/mascot"
HEADER = "/* GENERATED by assets/mascot/tools/build.py from assets/mascot/mascot.json — do not edit. */"


def manifest() -> dict:
    return json.loads((SRC / "mascot.json").read_text())


def pct(v: float) -> str:
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return s + "%"


def css(m: dict) -> str:
    fps = m["fps"]
    out = [HEADER, "",
           "/* <span class=\"mascot\" data-clip=\"idle\" style=\"--mascot-size: 48px\"></span> — the 1A chick (mascot.json).",
           "   One-shot clips stop on their last frame (`animationend` fires); set data-clip again to replay. */",
           ".mascot {",
           "  display: inline-block;",
           "  flex: none;",
           "  width: var(--mascot-size, 80px);",
           "  height: var(--mascot-size, 80px);",
           "  background-repeat: no-repeat;",
           "  background-size: auto 100%;",
           "  vertical-align: middle;",
           "}"]
    for name, c in m["clips"].items():
        n = c["frames"]
        pos = lambda f: pct(100 * f / (n - 1))   # noqa: E731
        total = sum(t for _, t in c["timeline"])
        secs = total / fps
        frames, acc = [], 0
        for f, t in c["timeline"]:
            frames.append(f"  {pct(100 * acc / total)} {{ background-position-x: {pos(f)}; }}")
            acc += t
        frames.append(f"  100% {{ background-position-x: {pos(c['timeline'][-1][0])}; }}")
        out += ["", f"@keyframes blurt-mascot-{name} {{", *frames, "}",
                f".mascot[data-clip=\"{name}\"] {{",
                f"  background-image: url(\"./{c['sheet']}.webp\");",
                f"  background-position-x: {pos(c['timeline'][-1][0] if not c['loop'] else c['timeline'][0][0])};",
                f"  animation: blurt-mascot-{name} {secs:.3f}s steps(1, end) {'infinite' if c['loop'] else '1 forwards'};",
                "}"]
    out += ["", "@media (prefers-reduced-motion: reduce) {",
            "  .mascot { animation: none !important; }"]
    for name, c in m["clips"].items():
        out.append(f"  .mascot[data-clip=\"{name}\"] {{ background-position-x: {pct(100 * c['still'] / (c['frames'] - 1))}; }}")
    out += ["}", "",
            "/* The 4A line glyph (`chicken` / `blurt` icons) moves in code, not frames: a head tilt while listening, a",
            "   small hop when something is done. Put the class on the icon's <svg class=\"ico\">. */",
            ".ico.tilt { transform-origin: 50% 80%; animation: blurt-glyph-tilt 1.4s ease-in-out infinite; }",
            ".ico.hop { transform-origin: 50% 100%; animation: blurt-glyph-hop 0.62s cubic-bezier(.3, .7, .4, 1) 1; }",
            "@keyframes blurt-glyph-tilt { 0%, 100% { transform: rotate(0deg); } 35%, 65% { transform: rotate(-12deg); } }",
            "@keyframes blurt-glyph-hop {",
            "  0% { transform: translateY(0) scale(1, 1); }",
            "  18% { transform: translateY(0) scale(1.12, .86); }",
            "  45% { transform: translateY(-28%) scale(.94, 1.08); }",
            "  72% { transform: translateY(0) scale(1.08, .92); }",
            "  100% { transform: translateY(0) scale(1, 1); }",
            "}",
            "@media (prefers-reduced-motion: reduce) { .ico.tilt, .ico.hop { animation: none; } }", ""]
    return "\n".join(out)


def outputs(m: dict) -> dict[Path, bytes]:
    files: dict[Path, bytes] = {}
    sheets = sorted({c["sheet"] for c in m["clips"].values()})
    for dest in (WEB,):
        for s in sheets:
            files[dest / f"{s}.webp"] = (SRC / f"{s}.webp").read_bytes()
        files[dest / "mascot.json"] = (SRC / "mascot.json").read_bytes()
    files[WEB / "mascot.css"] = css(m).encode()
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = outputs(manifest())
    if a.check:
        stale = [str(p.relative_to(REPO)) for p, b in files.items() if not p.exists() or p.read_bytes() != b]
        extra = [str(p.relative_to(REPO)) for d in (WEB,) if d.exists() for p in d.iterdir()
                 if p.is_file() and p not in files]
        if stale or extra:
            print("mascot outputs out of date (run python3 assets/mascot/tools/build.py):", *stale, *extra, sep="\n  ")
            return 1
        return 0
    for d in (WEB,):
        if d.exists():
            shutil.rmtree(d)
        d.mkdir(parents=True)
    for p, b in files.items():
        p.write_bytes(b)
    total = sum((SRC / f"{s}.webp").stat().st_size for s in {c["sheet"] for c in manifest()["clips"].values()})
    print(f"mascot: {len(files)} files written; strips {total / 1024:.0f} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
