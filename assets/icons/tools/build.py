"""Generates every platform's icons from the hand-written SVGs in assets/icons/ (the single source of truth).

    python3 assets/icons/tools/build.py            # write all outputs
    python3 assets/icons/tools/build.py --check    # exit 1 if a committed output is stale (tests run this)

Outputs
  Swift  skills/blurt/recorder/macos/Sources/BlurtApp/Icons/BlurtIconPaths.swift   enum BlurtIcon + CGPath code
  Web    web/packages/icons/src/generated.ts     icon geometry, names, aliases, kind-egg sprite
         web/packages/icons/sprite.svg           <symbol id="bi-NAME"> + <symbol id="egg-KIND"> (for single-file pages)
  Tk     skills/blurt/assets/icons/NAME.png, @1.5x, @2x   16 pt light glyphs for the dark Tk HUD
         skills/blurt/assets/icons/egg-KIND.png, @2x       the kind eggs
         (PNGs need rsvg-convert; --check only verifies they exist, and --no-png skips them)
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import iconlib  # noqa: E402
from iconlib import fmt  # noqa: E402

REPO = iconlib.REPO
SWIFT_OUT = REPO / "skills/blurt/recorder/macos/Sources/BlurtApp/Icons/BlurtIconPaths.swift"
TS_OUT = REPO / "web/packages/icons/src/generated.ts"
SPRITE_OUT = REPO / "web/packages/icons/sprite.svg"
PNG_DIR = REPO / "skills/blurt/assets/icons"
PNG_COLOR = "#f4f4f5"      # FG of tk_recorder.py's dark bar
PNG_SIZE = 16
SPRITE_OPEN = ('<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true" '
               'focusable="false"><defs>')
HEADER = "GENERATED by assets/icons/tools/build.py from assets/icons/*.svg — do not edit; edit the SVGs and rerun."


def mapping():
    return json.loads((iconlib.ICONS_DIR / "sf-symbols.json").read_text())


def swift_case(name: str) -> str:
    parts = name.split("-")
    s = parts[0] + "".join(p.capitalize() for p in parts[1:])
    return f"`{s}`" if s in ("repeat", "return", "default", "case", "in", "is", "as", "func", "import") else s


def swift_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen_swift(icons) -> str:
    m = mapping()
    sf, nearest, aliases = m["generic"], m["nearest"], m["aliases"]
    for n in list(sf) + list(nearest) + list(aliases.values()):
        if n not in {i.name for i in icons}:
            raise SystemExit(f"sf-symbols.json names an unknown icon: {n}")
    o = [f"// {HEADER}", "//", "// The geometry lives in the 24×24 grid, y down, exactly as in the SVGs; BlurtIcon.swift draws it.", "",
         "import CoreGraphics", "",
         "/// Every icon in the blurt family (assets/icons/*.svg). Brand glyphs are always drawn from these vectors;",
         "/// generic ones prefer the matching SF Symbol on macOS (see `sfSymbols`, BlurtIcon.symbolImage).",
         "enum BlurtIcon: String, CaseIterable {"]
    for ic in icons:
        o.append(f"    case {swift_case(ic.name)} = {swift_str(ic.name)}")
    o += ["}", "", "extension BlurtIcon {",
          "    /// Other names that resolve to the same icon (same table as the web package's ALIASES).",
          "    static let aliases: [String: BlurtIcon] = ["]
    for a, t in sorted(aliases.items()):
        o.append(f"        {swift_str(a)}: .{swift_case(t)},")
    o += ["    ]", "",
          "    /// \"brand\" (our own glyph everywhere) or \"generic\" (an SF Symbol on macOS when one exists).",
          "    var group: String {", "        switch self {"]
    gen = [i for i in icons if i.group == "generic"]
    if gen:
        o.append("        case " + ", ".join("." + swift_case(i.name) for i in gen) + ": return \"generic\"")
    o += ["        default: return \"brand\"", "        }", "    }", "",
          "    /// SF Symbol names to try, best first (empty for brand glyphs).",
          "    var sfSymbols: [String] {", "        switch self {"]
    for n, names in sf.items():
        o.append(f"        case .{swift_case(n)}: return [{', '.join(swift_str(x) for x in names)}]")
    o += ["        default: return []", "        }", "    }", "",
          "    /// Accessibility description (English; callers localize where it is shown as text).",
          "    var title: String {", "        switch self {"]
    for ic in icons:
        o.append(f"        case .{swift_case(ic.name)}: return {swift_str(ic.title or ic.name)}")
    o += ["        }", "    }", "",
          "    /// The painted layers, in order. Strokes use the family width (1.75 in grid units, scaled with the icon).",
          "    func makeLayers() -> [BlurtIconLayer] {", "        switch self {"]
    for ic in icons:
        o.append(f"        case .{swift_case(ic.name)}:")
        o.append("            return [")
        for L in ic.layers:
            mode = ".stroke" if L.mode == "stroke" else ".fill"
            op = f", opacity: {fmt(L.opacity)}" if L.opacity != 1 else ""
            o.append(f"                BlurtIconLayer({mode}{op}) {{ p in")
            line = []
            for c, a in L.segs:
                v = ", ".join(fmt(x) for x in a)
                line.append({"M": f"p.m({v})", "L": f"p.l({v})", "C": f"p.c({v})", "Z": "p.z()"}[c])
            # wrap to keep lines readable
            cur = "                    "
            for st in line:
                piece = st + "; "
                if len(cur) + len(piece) > 140:
                    o.append(cur.rstrip())
                    cur = "                    "
                cur += piece
            o.append(cur.rstrip().rstrip(";"))
            o.append("                },")
        o.append("            ]")
    o += ["        }", "    }", "}", ""]
    return "\n".join(o)


def ts_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def egg_symbols():
    """Kind eggs → ([defs…], [<symbol id="egg-KIND">…]) for one shared sprite."""
    defs, syms = [], []
    for k, svg in iconlib.egg_svgs().items():
        svg = re.sub(r"<title>.*?</title>", "", svg, flags=re.S)
        d = re.search(r"<defs>(.*?)</defs>", svg, re.S)
        if d:
            defs.append(d.group(1).strip())
            svg = svg.replace(d.group(0), "")
        body = re.sub(r"^\s*<svg[^>]*>|</svg>\s*$", "", svg.strip()).strip()
        body = re.sub(r">\s+<", "><", body)
        syms.append(f'<symbol id="egg-{k}" viewBox="0 0 16 16">{body}</symbol>')
    return defs, syms


def gen_sprite(icons) -> str:
    defs, eggs = egg_symbols()
    out = [f"<!-- {HEADER} -->", SPRITE_OPEN]
    out += defs
    for ic in icons:
        out.append(f'<symbol id="bi-{ic.name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="{iconlib.STROKE}" '
                   f'stroke-linecap="round" stroke-linejoin="round">{iconlib.inner_markup(ic)}</symbol>')
    out += eggs
    out.append("</defs></svg>")
    return "\n".join(out) + "\n"


def gen_ts(icons) -> str:
    m = mapping()
    o = [f"// {HEADER}", "/* eslint-disable */", "",
         "/** One painted shape: [mode, d, opacity?] — mode 0 = stroke (1.75, round caps/joins), 1 = fill; currentColor. */",
         "export type IconLayer = readonly [0 | 1, string, number?];", "",
         "export const ICONS = {"]
    for ic in icons:
        layers = ", ".join(
            "[" + ("0" if L.mode == "stroke" else "1") + ", " + ts_str(L.d) + (f", {fmt(L.opacity)}" if L.opacity != 1 else "") + "]"
            for L in ic.layers)
        o.append(f"  {ts_str(ic.name)}: [{layers}],")
    o += ["} as const satisfies Record<string, readonly IconLayer[]>;", "",
          "export type CanonicalIconName = keyof typeof ICONS;", "",
          "export const ALIASES = {"]
    for a, t in sorted(m["aliases"].items()):
        o.append(f"  {ts_str(a)}: {ts_str(t)},")
    o += ["} as const satisfies Record<string, CanonicalIconName>;", "",
          "export const GROUPS: Record<CanonicalIconName, \"brand\" | \"generic\"> = {"]
    for ic in icons:
        o.append(f"  {ts_str(ic.name)}: {ts_str(ic.group)},")
    o += ["};", "", "export const TITLES: Record<CanonicalIconName, string> = {"]
    for ic in icons:
        o.append(f"  {ts_str(ic.name)}: {ts_str(ic.title or ic.name)},")
    defs, eggs = egg_symbols()
    sprite = "".join([SPRITE_OPEN] + defs + eggs + ["</defs></svg>"])
    o += ["};", "",
          "/** Kind eggs (16×16, full colour; egg-custom is tinted with currentColor). One copy of this per page. */",
          f"export const EGG_SPRITE = {ts_str(sprite)};", ""]
    return "\n".join(o)


def write(path: Path, text: str, check: bool, stale: list):
    old = path.read_text() if path.exists() else None
    if old == text:
        return
    if check:
        stale.append(str(path.relative_to(REPO)))
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print("wrote", path.relative_to(REPO))


def render_png(svg: str, px: int, out: Path):
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), "-f", "png", "-o", str(out)], input=svg.encode(), check=True)


def pngs(icons, check: bool, stale: list):
    want = []
    densities = ((1, ""), (1.5, "@1.5x"), (2, "@2x"))     # Tk doesn't scale images: one file per screen density
    for ic in icons:
        svg = iconlib.normalized_svg(ic, PNG_COLOR)
        want += [(svg, int(PNG_SIZE * d), PNG_DIR / f"{ic.name}{sfx}.png") for d, sfx in densities]
    for k, svg in iconlib.egg_svgs().items():
        svg = svg.replace("currentColor", "#cfe3b0")
        want += [(svg, int(PNG_SIZE * d), PNG_DIR / f"egg-{k}{sfx}.png") for d, sfx in densities]
    if check:
        stale += [str(p.relative_to(REPO)) for _, _, p in want if not p.exists()]
        return
    if not shutil.which("rsvg-convert"):
        print("rsvg-convert not found: PNGs not rendered (brew install librsvg)", file=sys.stderr)
        return
    keep = {p for _, _, p in want}
    for p in PNG_DIR.glob("*.png"):
        if p not in keep:
            p.unlink()
    for svg, px, p in want:
        render_png(svg, px, p)
    print(f"rendered {len(want)} PNGs into", PNG_DIR.relative_to(REPO))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--no-png", action="store_true")
    a = ap.parse_args()
    icons = iconlib.load_all()
    errs = [e for ic in icons for e in iconlib.lint(ic)]
    if errs:
        raise SystemExit("\n".join(errs))
    stale: list[str] = []
    write(SWIFT_OUT, gen_swift(icons), a.check, stale)
    write(TS_OUT, gen_ts(icons), a.check, stale)
    write(SPRITE_OUT, gen_sprite(icons), a.check, stale)
    if not a.no_png:
        pngs(icons, a.check, stale)
    if stale:
        raise SystemExit("stale icon outputs (run python3 assets/icons/tools/build.py):\n  " + "\n  ".join(stale))
    if a.check:
        print(f"{len(icons)} icons, outputs up to date")


if __name__ == "__main__":
    main()
