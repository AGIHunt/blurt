# ---------------------------------------------------------------------------------------------------- colour maths
def rgba(h: str) -> tuple[float, float, float, float]:
    h = h.lstrip("#")
    a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
    return int(h[0:2], 16) / 255, int(h[2:4], 16) / 255, int(h[4:6], 16) / 255, a


def over(fg: str, bg: str) -> str:
    """fg (with alpha) composited over an opaque bg, as hex."""
    r, g, b, a = rgba(fg)
    R, G_, B, _ = rgba(bg)
    return "#" + "".join(f"{round((x * a + y * (1 - a)) * 255):02X}" for x, y in ((r, R), (g, G_), (b, B)))


def lum(h: str) -> float:
    def ch(x):
        return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4
    r, g, b, _ = rgba(h)
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def contrast(a: str, b: str) -> float:
    x, y = lum(a), lum(b)
    return (max(x, y) + 0.05) / (min(x, y) + 0.05)


def mix(a: str, b: str, t: float) -> str:
    """sRGB interpolation (what CAGradientLayer and CSS gradients do), t = 0 → a."""
    A, B = rgba(a), rgba(b)
    return "#" + "".join(f"{round((x + (y - x) * t) * 255):02X}" for x, y in zip(A[:3], B[:3]))


def scale(h: str, k: float) -> str:
    """CSS filter: brightness(k)."""
    r, g, b, _ = rgba(h)
    return "#" + "".join(f"{round(min(1, x * k) * 255):02X}" for x in (r, g, b))


def hue(h: str) -> float:
    """OKLab hue in degrees."""
    def ch(x):
        return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4
    r, g, b, _ = (ch(v) if i < 3 else v for i, v in enumerate(rgba(h)))
    l_ = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3)
    m_ = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3)
    s_ = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
    a = 1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_
    bb = 0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_
    return math.degrees(math.atan2(bb, a)) % 360


def stop_hex(name: str) -> str:
    return G["stops"].get(name, name)


def stops(lst) -> list[tuple[str, float]]:
    return [(stop_hex(c), float(at)) for c, at in lst]


def samples(st: list[tuple[str, float]], n: int = 24) -> list[str]:
    """Colours along a gradient, every stop plus n even steps."""
    out = [c for c, _ in st]
    for i in range(n + 1):
        t = i / n
        for (c0, a0), (c1, a1) in zip(st, st[1:]):
            if a0 <= t <= a1:
                out.append(mix(c0, c1, 0 if a1 == a0 else (t - a0) / (a1 - a0)))
                break
    return out


def tok(path: str) -> dict:
    g, n = path.split(".")
    return T[g][n]


# ---------------------------------------------------------------------------------------------------- checks
def check_contrast() -> list[str]:
    errs = []
    C = T["checks"]

    def need(what, ratio, floor):
        if ratio + 1e-9 < floor:
            errs.append(f"{what}: {ratio:.2f} < {floor}")

    for group in ("brand", "semantic", "kind"):
        for name, t in T[group].items():
            if not isinstance(t, dict) or "min" not in t:
                continue
            floor = t["min"]
            for mode in ("light", "dark", "island"):
                if mode not in t:
                    continue
                vals = [(mode, t[mode])] + ([(f"hc {mode}", t["hc"][mode])] if mode in t.get("hc", {}) else [])
                for label, v in vals:
                    if "on" in t:      # a colour for glyphs on another token
                        base = tok(t["on"])[mode]
                        need(f"{group}.{name} {label} on {t['on']}", contrast(v, base), floor)
                        continue
                    surfaces = list(C.get(mode, []))
                    if group == "kind":
                        surfaces.append(C["kindSurfaces"][mode])
                    for s in surfaces:
                        need(f"{group}.{name} {label} on {s}", contrast(v, s), floor)
            if "onWhite" in t:
                for mode in ("light", "dark"):
                    need(f"{group}.{name} white on {mode}", contrast("#FFFFFF", t[mode]), t["onWhite"])
    # text on the tint: the tint is a wash, text on it stays ink; brand.ink on it must still read
    for mode in ("light", "dark"):
        for s in C[mode]:
            need(f"brand.ink on brand.tint ({mode}, over {s})", contrast(T["brand"]["ink"][mode], over(T["brand"]["tint"][mode], s)), 4.5)
    # gradients
    lin = stops(G["linear"]["stops"])
    for c in samples(lin):
        need(f"gradient.linear: {G['linear']['on']} on {c}", contrast(G["linear"]["on"], c), G["linear"]["onMin"])
    b = G["button"]
    for c in samples(stops(b["stops"])):
        need(f"gradient.button: {b['on']} on {c}", contrast(b["on"], c), b["onMin"])
        need(f"gradient.button hover: {b['on']} on {scale(c, b['hover'])}", contrast(b["on"], scale(c, b["hover"])), b["hoverMin"])
    for mode in ("light", "dark"):
        tx = G["text"][mode]
        for c in samples(stops(tx["stops"])):
            for s in C[mode]:
                need(f"gradient.text.{mode} {c} on {s}", contrast(c, s), tx["min"])
    for c in G["deep"]["stops"].values():
        need(f"gradient.deep: brand.on on {c}", contrast(T["brand"]["on"]["light"], c), G["deep"]["onMin"])
    lo, hi = T["kind"]["customHueGap"]
    if not (0 <= lo < hi <= 360):
        errs.append("kind.customHueGap must be [lo, hi] in degrees")
    # the four kinds must not read as the brand mint: OKLab hue at least 20° away from brand.fill
    mint_h = hue(T["brand"]["fill"]["light"])
    for k in ("issue", "idea", "note", "task"):
        for mode in ("light", "dark"):
            d = abs((hue(T["kind"][k][mode]) - mint_h + 180) % 360 - 180)
            if d < 20:
                errs.append(f"kind.{k} {mode} is {d:.0f}° from the brand hue")
    return errs


# ---------------------------------------------------------------------------------------------------- Swift
def sx(h: str) -> str:
    """Swift `0xRRGGBB` literal (alpha separately)."""
    return "0x" + h.lstrip("#")[:6].upper()


def salpha(h: str) -> str:
    a = rgba(h)[3]
    return "1" if a == 1 else f"{a:.3f}".rstrip("0")


def swift_color(t: dict, mode_l="light", mode_d="dark") -> str:
    l, d = t[mode_l], t[mode_d]
    hc = t.get("hc", {})
    args = f"{sx(l)}, {salpha(l)}, {sx(d)}, {salpha(d)}"
    if hc:
        hl, hd = hc.get("light", l), hc.get("dark", d)
        args += f", hc: ({sx(hl)}, {salpha(hl)}, {sx(hd)}, {salpha(hd)})"
    return f"dynamic({args})"


def swift_static(t: dict, mode: str) -> str:
    v = t[mode]
    return f"srgb({sx(v)}, {salpha(v)})"


def swift_stops(st) -> str:
    return "[" + ", ".join(f"({sx(c)}, {at:g})" for c, at in st) + "]"


def swift_field(layers) -> str:
    out = []
    for L in layers:
        st = ", ".join(f"({sx(c)}, {a:g}, {at:g})" for c, a, at in L["stops"])
        if L["type"] == "linear":
            out.append(f"        .linear(stops: [{st}])")
        else:
            (cx, cy), (rx, ry) = L["center"], L["radius"]
            out.append(f"        .radial(center: CGPoint(x: {cx:g}, y: {cy:g}), radius: CGSize(width: {rx:g}, height: {ry:g}), stops: [{st}])")
    return "[\n" + ",\n".join(out) + ",\n    ]"


