def colorset() -> str:
    def comp(h):
        r, g, b, a = rgba(h)
        return {"alpha": f"{a:.3f}", "blue": f"0x{round(b * 255):02X}", "green": f"0x{round(g * 255):02X}",
                "red": f"0x{round(r * 255):02X}"}
    a = T["brand"]["accent"]
    colors = [
        {"color": {"color-space": "srgb", "components": comp(a["light"])}, "idiom": "universal"},
        {"appearances": [{"appearance": "luminosity", "value": "dark"}],
         "color": {"color-space": "srgb", "components": comp(a["dark"])}, "idiom": "universal"},
    ]
    return json.dumps({"colors": colors, "info": {"author": "xcode", "version": 1}}, indent=2) + "\n"


CATALOG = json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n"


def compile_car() -> bytes | None:
    actool = shutil.which("actool") or (subprocess.run(["xcrun", "--find", "actool"], capture_output=True, text=True).stdout.strip()
                                        if shutil.which("xcrun") else "")
    if not actool or not Path(actool).exists():
        return None
    with tempfile.TemporaryDirectory() as t:
        r = subprocess.run([actool, "--compile", t, "--platform", "macosx", "--minimum-deployment-target", "13.0",
                            "--accent-color", "AccentColor", "--output-partial-info-plist", f"{t}/partial.plist",
                            "--output-format", "human-readable-text", "--notices", "--warnings", str(XCASSETS)],
                           capture_output=True, text=True)
        car = Path(t) / "Assets.car"
        if r.returncode != 0 or not car.exists():
            print(r.stdout, r.stderr, file=sys.stderr)
            return None
        return car.read_bytes()


def car_colors() -> dict | None:
    """The AccentColor entries in the compiled Assets.car, via assetutil: {appearance: (r, g, b)} in 0–255."""
    if not shutil.which("assetutil") or not CAR.exists():
        return None
    r = subprocess.run(["assetutil", "--info", str(CAR)], capture_output=True, text=True)
    if r.returncode != 0:
        return None
    out = {}
    for e in json.loads(r.stdout):
        if e.get("Name") == "AccentColor" and "Color components" in e:
            comps = e["Color components"]
            out[e.get("Appearance", "UIAppearanceAny")] = tuple(round(c * 255) for c in comps[:3])
    return out


def check_car() -> list[str]:
    got = car_colors()
    if got is None:
        return [] if CAR.exists() else [f"{CAR.relative_to(REPO)} is missing (run build.py on a Mac with Xcode)"]
    a = T["brand"]["accent"]
    want_l = tuple(round(x * 255) for x in rgba(a["light"])[:3])
    want_d = tuple(round(x * 255) for x in rgba(a["dark"])[:3])
    errs = []
    if want_l not in got.values():
        errs.append(f"Assets.car: AccentColor light {a['light']} not found ({got}); rerun build.py")
    if not any(k.endswith("DarkAqua") or "Dark" in k for k in got) or want_d not in got.values():
        errs.append(f"Assets.car: AccentColor dark {a['dark']} not found ({got}); rerun build.py")
    return errs


# ---------------------------------------------------------------------------------------------------- table
def table() -> str:
    C = T["checks"]
    rows = ["| Token | Light | on light surfaces | Dark | on dark surfaces | Island |", "|---|---|---|---|---|---|"]
    for group in ("brand", "semantic", "kind"):
        for name, t in T[group].items():
            if not isinstance(t, dict) or "light" not in t:
                continue

            def cell(mode):
                v = t[mode]
                if "on" in t:
                    return f"{contrast(v, tok(t['on'])[mode]):.2f} on {t['on']}"
                if rgba(v)[3] < 1:
                    return "wash"
                return " / ".join(f"{contrast(v, s):.2f}" for s in C[mode])
            rows.append(f"| `{group}.{name}` | `{t['light']}` | {cell('light')} | `{t['dark']}` | {cell('dark')} | "
                        f"{('`' + t['island'] + '`') if 'island' in t else '—'} |")
    lines = ["\n".join(rows), ""]
    for label, st, on in (("linear", stops(G["linear"]["stops"]), G["linear"]["on"]),
                          ("button", stops(G["button"]["stops"]), G["button"]["on"])):
        s = samples(st)
        lines.append(f"gradient.{label}: {', '.join(c for c, _ in st)}; {on} on it ≥ {min(contrast(on, c) for c in s):.2f}")
    b = G["button"]
    lines.append(f"gradient.button hover ×{b['hover']}: white ≥ {min(contrast('#FFFFFF', scale(c, b['hover'])) for c in samples(stops(b['stops']))):.2f}")
    for mode in ("light", "dark"):
        st = stops(G["text"][mode]["stops"])
        lines.append(f"gradient.text.{mode}: {', '.join(c for c, _ in st)}; ≥ "
                     f"{min(contrast(c, s) for c in samples(st) for s in C[mode]):.2f} on {mode} surfaces")
    lines.append(f"gradient.spectrum: {', '.join(c for c, _ in stops(G['spectrum']['stops']))}")
    a = T["brand"]["accent"]
    lines.append(f"brand.accent: white on light {contrast('#FFFFFF', a['light']):.2f}, on dark {contrast('#FFFFFF', a['dark']):.2f}")
    return "\n".join(lines)


# ---------------------------------------------------------------------------------------------------- main
def outputs() -> list[tuple[Path, str]]:
    return [
        (SWIFT_OUT, gen_swift()),
        (UI_CSS, splice(UI_CSS.read_text(), gen_ui_block(), UI_CSS)),
        (OVERLAY_CSS, splice(OVERLAY_CSS.read_text(), gen_overlay_block(), OVERLAY_CSS)),
        (XCASSETS / "Contents.json", CATALOG),
        (ACCENT_SET, colorset()),
    ]


def main() -> int:
    if "--table" in sys.argv:
        print(table())
        return 0
    errs = check_contrast()
    if "--check" in sys.argv:
        for p, want in outputs():
            if not p.exists() or p.read_text() != want:
                errs.append(f"{p.relative_to(REPO)} is stale: run python3 assets/color/build.py")
        errs += check_car()
        for e in errs:
            print("FAIL", e)
        if not errs:
            print("colour outputs up to date; contrast floors hold")
        return 1 if errs else 0
    if errs:
        for e in errs:
            print("FAIL", e)
        return 1
    for p, text in outputs():
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
            print("wrote", p.relative_to(REPO))
    car = compile_car()
    if car is None:
        print("actool not available: Assets.car not rebuilt (needs Xcode)", file=sys.stderr)
    elif not CAR.exists() or check_car():
        CAR.write_bytes(car)
        print("wrote", CAR.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
