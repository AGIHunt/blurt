"""Renders every brand bitmap from the vector sources in assets/brand/ (the 4A line chick, v0.8).

    swift assets/brand/chick.swift            # first, if the geometry or a tokens.json gradient changed: rewrites the SVGs
    python3 assets/brand/build.py             # write everything below except site/
    python3 assets/brand/build.py --site      # also the site/ outputs (for the site redo; off by default)
    python3 assets/brand/build.py --list      # just print the outputs

Sources (SVG, generated by chick.swift; 1024 canvas; the tile colours come from assets/color/tokens.json):
  app-icon.svg         the master app icon — 824 px superellipse tile at (100, 100) on the macOS 26 grid, soft shadow,
                       3 px white rim; the tile is gradient.field (#tile-field) with grain (#tile-grain, dropped
                       below 64 px); group #chick = the chick
  app-icon-small.svg   the 32 px slot (16@2x) and the favicon: heavier line, one sound arc, filled beak; plain
                       gradient.linear tile
  app-icon-16.svg      the 16 px slot: no arcs, chunkier still; plain gradient.linear tile
  app-icon-dark.svg    the master on gradient.deep (the optional dark appearance; not rendered here, see README)
  logo.svg             the chick without the tile on a white sticker edge, transparent (README, site)
  glyph.svg            the menu-bar / tray glyph (24 grid, filled outlines) — a copy lives at assets/icons/blurt.svg,
                       which assets/icons/tools/build.py turns into Swift / web / Tk / tray icons

Outputs
  skills/blurt/assets/icon.png            1024 master (record.py make_icns → Blurt.app AppIcon.icns; review page logo)
  skills/blurt/assets/icon-16.png, -32.png the small variants for the icns 16 / 32 px slots
  assets/logo.png                         the logo, transparent, 1024 (README)
  site/assets/…  (only with --site)
  site/assets/logo.png                    the same at 320 (site header / footer)
  site/assets/favicon.png                 64, small variant, tile cropped
  site/assets/apple-touch-icon.png        180, full-bleed square (iOS masks it)
  site/assets/og.png                      the social card: the left-hand logo slot is repainted with the logo; the
                                          text on the right is left as it is
  apps/desktop/src-tauri/icons/           32x32 / 64x64 / 128x128 / 128x128@2x / icon.png / icon.icns / icon.ico
  crates/blurt-capture/demo/icons/        32x32 / icon.png / icon.ico (the capture demo window)

Needs rsvg-convert (brew install librsvg) and Pillow; icon.icns needs macOS iconutil.
"""
from __future__ import annotations

import io
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
ICON = HERE / "app-icon.svg"
SMALL = HERE / "app-icon-small.svg"     # 17–32 px
TINY = HERE / "app-icon-16.svg"         # up to 16 px
LOGO = HERE / "logo.svg"


def svg(path: Path) -> str:
    return path.read_text()


def crop(src: str, vb: str) -> str:
    return re.sub(r'viewBox="[^"]*"', f'viewBox="{vb}"', src, count=1)


def full_bleed(src: str) -> str:
    """Square, no transparency (apple-touch-icon): the tile's field (#tile-field, unclipped: base, radial layers and
    grain) fills the whole 824 square, no shadow / rim; a plain tile becomes a square of #tile-bg."""
    tile = re.search(r'<g id="tile">\n.*?\n</g>\n', src, flags=re.S)
    assert tile, "app-icon.svg no longer has the #tile group build.py expects"
    field = re.search(r'<g id="tile-field"[^>]*>\n(.*?)\n  </g>', tile.group(0), flags=re.S)
    inner = field.group(1) if field else '<rect x="100" y="100" width="824" height="824" fill="url(#tile-bg)"/>'
    return crop(src.replace(tile.group(0), f'<g id="tile">\n{inner}\n</g>\n'), "100 100 824 824")


def no_grain(src: str) -> str:
    """The grain only shows at 64 px and up; below that it would just dirty the colour."""
    return re.sub(r'\s*<rect [^>]*id="tile-grain"[^>]*/>', "", src)


def render(src: str, px: int, w: int | None = None) -> bytes:
    if not shutil.which("rsvg-convert"):
        sys.exit("rsvg-convert not found (brew install librsvg)")
    return subprocess.run(["rsvg-convert", "-w", str(w or px), "-h", str(px), "-f", "png"], input=src.encode(),
                          capture_output=True, check=True).stdout


def icon_png(px: int) -> bytes:
    """≤ 16 px and ≤ 32 px: the small drawings, rendered directly. Larger: the master, rendered at 1024 and scaled
    down. rsvg-convert point-samples feTurbulence at the output pixel, so a direct 128 px render keeps the grain at full
    per-pixel strength; rendering at 1024 (where the grain's 0.6 frequency was set) and averaging down lets it fade with
    size the way WebKit / CSS draw it."""
    if px <= 32:
        return render(svg(TINY if px <= 16 else SMALL), px)
    src = svg(ICON) if px >= 64 else no_grain(svg(ICON))
    if px >= 1024:
        return render(src, px)
    from PIL import Image
    big = Image.open(io.BytesIO(render(src, 1024))).convert("RGBA")
    buf = io.BytesIO()
    big.resize((px, px), Image.LANCZOS).save(buf, format="PNG", optimize=True)
    return buf.getvalue()


def put(rel: str, data: bytes):
    p = REPO / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data)
    print("wrote", rel)


def ico(sizes) -> bytes:
    from PIL import Image
    imgs = [Image.open(io.BytesIO(icon_png(s))).convert("RGBA") for s in sizes]
    buf = io.BytesIO()
    imgs[-1].save(buf, format="ICO", sizes=[(s, s) for s in sizes], append_images=imgs[:-1])
    return buf.getvalue()


def icns() -> bytes | None:
    if not shutil.which("iconutil"):
        print("iconutil not found (macOS only): icon.icns not written", file=sys.stderr)
        return None
    with tempfile.TemporaryDirectory() as t:
        iconset = Path(t) / "AppIcon.iconset"
        iconset.mkdir()
        for s in (16, 32, 128, 256, 512):
            (iconset / f"icon_{s}x{s}.png").write_bytes(icon_png(s))
            (iconset / f"icon_{s}x{s}@2x.png").write_bytes(icon_png(s * 2))
        out = Path(t) / "icon.icns"
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(out)], check=True)
        return out.read_bytes()


def og() -> bytes:
    """The social card keeps its text; the logo slot on the left (x < 400) is cleared to the card's background and
    logo is placed there, centred where the old logo sat."""
    from PIL import Image
    p = REPO / "site/assets/og.png"
    card = Image.open(p).convert("RGB")
    bg = card.getpixel((4, 4))
    card.paste(bg, (0, 120, 398, 520))
    logo = Image.open(io.BytesIO(render(svg(LOGO), 280))).convert("RGBA")
    layer = Image.new("RGBA", card.size, (0, 0, 0, 0))
    layer.alpha_composite(logo, (222 - logo.width // 2, 312 - logo.height // 2))
    out = card.convert("RGBA")
    out.alpha_composite(layer)
    buf = io.BytesIO()
    out.convert("RGB").save(buf, format="PNG", optimize=True)
    return buf.getvalue()


def main():
    jobs = [
        ("skills/blurt/assets/icon.png", lambda: icon_png(1024)),
        ("skills/blurt/assets/icon-16.png", lambda: icon_png(16)),
        ("skills/blurt/assets/icon-32.png", lambda: icon_png(32)),
        ("assets/logo.png", lambda: render(svg(LOGO), 1024)),
        ("apps/desktop/src-tauri/icons/32x32.png", lambda: icon_png(32)),
        ("apps/desktop/src-tauri/icons/64x64.png", lambda: icon_png(64)),
        ("apps/desktop/src-tauri/icons/128x128.png", lambda: icon_png(128)),
        ("apps/desktop/src-tauri/icons/128x128@2x.png", lambda: icon_png(256)),
        ("apps/desktop/src-tauri/icons/icon.png", lambda: icon_png(512)),
        ("apps/desktop/src-tauri/icons/icon.ico", lambda: ico([16, 24, 32, 48, 64, 256])),
        ("apps/desktop/src-tauri/icons/icon.icns", icns),
        ("crates/blurt-capture/demo/icons/32x32.png", lambda: icon_png(32)),
        ("crates/blurt-capture/demo/icons/icon.png", lambda: icon_png(64)),
        ("crates/blurt-capture/demo/icons/icon.ico", lambda: ico([16, 32, 64])),
    ]
    site = [  # for the site redo: off unless --site
        ("site/assets/logo.png", lambda: render(svg(LOGO), 320)),
        ("site/assets/favicon.png", lambda: render(crop(svg(SMALL), "84 84 856 856"), 64)),
        ("site/assets/apple-touch-icon.png", lambda: render(full_bleed(svg(ICON)), 180)),
        ("site/assets/og.png", og),
    ]
    if "--site" in sys.argv:
        jobs += site
    if "--list" in sys.argv:
        print("\n".join(r for r, _ in jobs))
        return
    for rel, fn in jobs:
        data = fn()
        if data is not None:
            put(rel, data)
    glyph = (HERE / "glyph.svg").read_text()
    if (REPO / "assets/icons/blurt.svg").read_text() != glyph:
        print("note: assets/icons/blurt.svg differs from assets/brand/glyph.svg — copy it over and run "
              "python3 assets/icons/tools/build.py", file=sys.stderr)


if __name__ == "__main__":
    main()
