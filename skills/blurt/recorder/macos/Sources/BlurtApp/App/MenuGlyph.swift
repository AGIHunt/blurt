// The menu-bar chick moves a little, in code: while voice input listens two sound arcs come out of it and pulse
// outward (inner, then outer, like a voice carrying), and it hops once when something is done (an item fixed /
// confirmed, a batch organised). The status item can only show an image, so this swaps images at 24 fps — only while
// it moves. Reduce Motion: no timer; while listening it shows the arcs still (the state stays visible), else the plain
// icon.
//
// The chick is the template `blurt` glyph (assets/brand/glyph.svg — the 4A chick as a bold filled silhouette with the
// face knocked out, generated by assets/brand/chick.swift), like every other menu-bar icon. At rest it is the chick
// alone, 18 pt wide; the arcs (MenuGlyphGeometry.swift, from the same chick.swift) sit to its right, so while
// listening the image is wider (`listenWidth`) and the count moves over by that much — once, when listening starts,
// not per frame. Every frame is 22 pt tall (the bar) with the 18 pt box centred in it, so the hop has room above the
// tuft; AppKit centres the 18 pt rest image the same way, so the chick never jumps between the two.
import AppKit
import BlurtCore

final class MenuGlyph {
    static let shared = MenuGlyph()
    /// What the status item shows right now while it moves (nil = the plain icon).
    private(set) var current: NSImage?
    var onFrame: ((NSImage?) -> Void)?

    private var timer: Timer?
    private var pulseSince: CFTimeInterval?
    private var hopSince: CFTimeInterval?
    private var cache: [String: NSImage] = [:]

    /// The glyph's box (the rest icon is this square) and the frames' height (the menu bar's).
    static let box: CGFloat = 18
    static let barHeight: CGFloat = 22
    /// The image while listening: the box plus the arcs, with a point of air after them.
    static let listenWidth: CGFloat = ceil(arcsRight + 1)

    /// v0.8 betas had a colour menu-bar hen behind Settings → General (app.menu_icon_color, before that
    /// app.menu_icon_mono). The chick is monochrome only, so the old keys just go.
    static func migrateSetting() {
        for k in ["app.menu_icon_mono", "app.menu_icon_color"] where Config.shared[k] != nil { Config.shared.set(k, nil) }
    }

    /// Voice input listening (the island and the status item follow it).
    var listening = false {
        didSet {
            guard listening != oldValue else { return }
            pulseSince = listening ? CACurrentMediaTime() : nil
            run()
        }
    }

    func hop() {
        hopSince = CACurrentMediaTime()
        run()
    }

    private var moving: Bool { pulseSince != nil || hopSince != nil }

    private func run() {
        if reduceMotion || !moving {
            timer?.invalidate(); timer = nil
            hopSince = nil
            // Reduce Motion while listening: the arcs, still; otherwise the plain icon
            current = listening ? MenuGlyph.stillListening : nil
            onFrame?(current)
            return
        }
        guard timer == nil else { return }
        let t = Timer(timeInterval: 1.0 / 24, repeats: true) { [weak self] _ in self?.frame() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
        frame()
    }

    private static let stillListening: NSImage = {
        let i = pose(arcs: (1, 1))
        i.accessibilityDescription = T("app.name")
        return i
    }()

    /// How high the hop goes (pt) and how much it stretches (a fraction of the height, about the foot). The tuft's top
    /// is 2.8 pt below the frame's top (the chick is 16.2 pt tall, foot at 17 of its 18 pt box): lift + 16.2 × stretch must
    /// stay under that or the tuft clips.
    static let hopHeight: CGFloat = 1.5
    static let hopStretch: CGFloat = 0.05
    /// The arcs' opacity at the dim end of a pulse.
    static let arcLow: CGFloat = 0.25

    /// One pulse cycle at `u` (0…1): the inner arc, then the outer one a quarter cycle later, each dipping to `arcLow`
    /// and swelling back — a voice going out.
    static func arcAlphas(_ u: Double) -> (CGFloat, CGFloat) {
        func swell(_ v: Double) -> CGFloat {
            let w = v - floor(v)                                    // 0…1
            let e = CGFloat(0.5 - 0.5 * cos(2 * .pi * w))           // 0 → 1 → 0
            return arcLow + (1 - arcLow) * (1 - e)                  // 1 → low → 1
        }
        return (swell(u), swell(u - 0.25))
    }

    private func frame() {
        if reduceMotion { run(); return }      // turned on mid-move: back to the still icon
        let now = CACurrentMediaTime()
        var arcs: (CGFloat, CGFloat)?, lift: CGFloat = 0, squash: CGFloat = 0
        if let s = pulseSince {
            arcs = MenuGlyph.arcAlphas((now - s) / 1.2)
        }
        if let s = hopSince {
            let u = (now - s) / 0.62
            if u >= 1 {
                hopSince = nil
            } else {
                // squash (crouch) → up, stretched → land, squash → rest
                lift = u < 0.18 ? 0 : u < 0.72 ? MenuGlyph.hopHeight * CGFloat(sin(.pi * (u - 0.18) / 0.54)) : 0
                squash = u < 0.18 ? 0.1 * CGFloat(sin(.pi * u / 0.36)) : u < 0.72 ? -MenuGlyph.hopStretch * CGFloat(sin(.pi * (u - 0.18) / 0.54))
                    : 0.07 * CGFloat(sin(.pi * (u - 0.72) / 0.28))
            }
        }
        guard moving else { run(); return }
        // quantised, so a few dozen images cover every frame
        let q = { (v: CGFloat) in (v * 50).rounded() / 50 }
        let qa = arcs.map { (q($0.0), q($0.1)) }
        let key = "\(qa.map { "\($0.0)|\($0.1)" } ?? "-")|\(q(lift))|\(q(squash))"
        let img = cache[key] ?? {
            let i = MenuGlyph.pose(arcs: qa, lift: q(lift), squash: q(squash))
            i.accessibilityDescription = T("app.name")
            cache[key] = i
            return i
        }()
        current = img
        onFrame?(img)
    }

    /// One frame, a template image `barHeight` tall: the chick in its 18 pt box (centred vertically), with the arcs at
    /// `arcs` opacity (inner, outer) to its right when listening (nil = no arcs, the box's width), lifted by `lift` pt
    /// and squashed by `squash` about its foot.
    static func pose(arcs: (CGFloat, CGFloat)? = nil, lift: CGFloat = 0, squash: CGFloat = 0) -> NSImage {
        let size = NSSize(width: arcs == nil ? box : listenWidth, height: barHeight)
        let img = NSImage(size: size, flipped: false) { _ in
            guard let ctx = NSGraphicsContext.current?.cgContext else { return false }
            let r = CGRect(x: 0, y: (barHeight - box) / 2, width: box, height: box)      // the glyph's box, y up
            let foot = r.maxY - MenuGlyph.foot
            ctx.translateBy(x: r.midX, y: foot + lift)
            ctx.scaleBy(x: 1 + squash, y: 1 - squash)
            ctx.translateBy(x: -r.midX, y: -foot)
            draw(in: ctx, rect: r, arcs: arcs)
            return true
        }
        img.isTemplate = true
        return img
    }

    /// Draws the `blurt` glyph into `rect` (its 18 pt box) of a y-up context, and the arcs (generated with it, in the
    /// box's y-down points; they reach past its right edge) at their opacities.
    static func draw(in ctx: CGContext, rect r: CGRect, arcs: (CGFloat, CGFloat)?) {
        BlurtIcon.blurt.draw(in: ctx, rect: r, color: CGColor(gray: 0, alpha: 1))
        guard let arcs else { return }
        let s = r.width / box
        ctx.saveGState()
        ctx.translateBy(x: r.minX, y: r.maxY)
        ctx.scaleBy(x: s, y: -s)                                    // the box's points, y down
        ctx.setLineWidth(arcLine)
        ctx.setLineCap(.round)
        for (i, a) in MenuGlyph.arcs.enumerated() {
            ctx.setStrokeColor(CGColor(gray: 0, alpha: i == 0 ? arcs.0 : arcs.1))
            ctx.addArc(center: arcCentre, radius: a.r, startAngle: a.from * .pi / 180, endAngle: a.to * .pi / 180, clockwise: false)
            ctx.strokePath()
        }
        ctx.restoreGState()
    }
}

extension MenuGlyph {
    /// Self-test (`menuglyph DIR`): the status item's images as the menu bar shows them, at 1x and 2x —
    ///   menuglyph-<pose>-<light|dark>@<n>x.png   the template chick (rest / listen-a / listen-b / listen-still /
    ///                                            hop / crouch) on a 22 pt strip, tinted like a template image (black
    ///                                            on a light bar, white on a dark one); listen-a / -b are two moments
    ///                                            of the arc pulse, listen-still the Reduce Motion one
    ///   statusbutton-<aqua|dark>-<rest|open|listen>@<n>x.png
    ///                                            the real status button (image + a stand-in count of 3) drawn in that
    ///                                            appearance, at rest, highlighted (its menu open) and with the
    ///                                            listening image (the arcs, so the count's shift shows) — transparent,
    ///                                            for a contact sheet on fake menu bars
    /// Returns the file names.
    @MainActor
    static func renderPoses(to dir: URL) -> [String] {
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        var names: [String] = []
        func bitmap(_ size: NSSize, scale: Int, _ draw: () -> Void) -> NSBitmapImageRep? {
            guard let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size.width) * scale, pixelsHigh: Int(size.height) * scale,
                                             bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                                             bytesPerRow: 0, bitsPerPixel: 0) else { return nil }
            rep.size = size                                       // `size` pt at `scale` pixels per point
            NSGraphicsContext.saveGraphicsState()
            NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
            draw()
            NSGraphicsContext.restoreGraphicsState()
            return rep
        }
        func write(_ rep: NSBitmapImageRep?, _ name: String) {
            if let d = rep?.representation(using: .png, properties: [:]), (try? d.write(to: dir.appendingPathComponent(name))) != nil {
                names.append(name)
            }
        }
        let poses: [(String, NSImage)] = [
            ("rest", App.makeMenuIcon()),
            ("listen-a", pose(arcs: arcAlphas(0.5))),
            ("listen-b", pose(arcs: arcAlphas(0.75))),
            ("listen-still", pose(arcs: (1, 1))),
            ("hop", pose(lift: hopHeight, squash: -hopStretch)),
            ("crouch", pose(squash: 0.1)),
        ]
        for (name, img) in poses {
            // every pose on a bar-high strip as wide as the image, the 18 pt rest icon centred like AppKit does
            let r = NSRect(x: 0, y: 0, width: img.size.width, height: barHeight)
            let at = NSRect(x: 0, y: ((barHeight - img.size.height) / 2).rounded(.down), width: img.size.width, height: img.size.height)
            for scale in [1, 2] {
                for (bar, tint) in [("light", NSColor.black), ("dark", NSColor.white)] {
                    write(bitmap(r.size, scale: scale) {
                        img.draw(in: at)
                        tint.set()
                        r.fill(using: .sourceIn)                  // a template image takes the menu bar's colour
                    }, "menuglyph-\(name)-\(bar)@\(scale)x.png")
                }
            }
        }
        // the real status button, in each appearance and state, with a count
        guard let app = NSApp.delegate as? App, let b = app.statusItem?.button else { return names }
        let savedAppearance = b.appearance
        MenuBadge.shared.testCount = 3
        defer {
            MenuBadge.shared.testCount = nil
            b.appearance = savedAppearance
            app.testMenuOpen(false)
        }
        for (name, appearance) in [("aqua", NSAppearance.Name.aqua), ("dark", .darkAqua)] {
            for state in ["rest", "open", "listen"] {
                b.appearance = NSAppearance(named: appearance)
                app.testMenuOpen(state == "open")                // refreshes the button
                if state == "listen" { b.image = stillListening }  // the wide listening image (refreshStatus puts it back)
                let size = NSSize(width: ceil(b.intrinsicContentSize.width), height: max(22, b.bounds.height))
                for scale in [1, 2] {
                    let frame = b.frame
                    b.setFrameSize(size)
                    let rep = bitmap(size, scale: scale) {
                        NSAppearance(named: appearance)?.performAsCurrentDrawingAppearance {
                            b.displayIgnoringOpacity(NSRect(origin: .zero, size: size), in: NSGraphicsContext.current!)
                        }
                    }
                    b.frame = frame
                    write(rep, "statusbutton-\(name)-\(state)@\(scale)x.png")
                }
            }
        }
        return names
    }
}
