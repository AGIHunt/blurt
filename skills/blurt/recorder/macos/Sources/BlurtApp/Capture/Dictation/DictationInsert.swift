// Typing the dictated text where the cursor is: save the user's pasteboard (every item, every type), put the text
// on it, ⌘V into the frontmost app, and put the old pasteboard back (unless something else changed it) once the paste
// has landed — the field shows the text (BlurtCore DictationPasteLanding; a double tap's Return goes then, 0.6 s at
// the latest), or, for a field that can't be read or never shows the text exactly, the clipboard after 1.5 s: a slow
// app never pastes the old clipboard because it was put back too early.
// BlurtCore's DictationPastePolicy decides, like Typeless: ⌘V into any other app in front, whatever its focused
// element looks like to Accessibility (WeChat's input box isn't a text role) —
//   • no app in front, secure input on / a password field, or no Accessibility (a posted ⌘V wouldn't arrive) →
//     the text stays on the clipboard and the island says "Copied — paste with ⌘V";
//   • a paste into a focus Accessibility can't read (WeChat) → the island offers "Copy again" for a few seconds;
//   • a paste into a focus Accessibility reads as something other than a text field (the desktop, a page with no
//     field focused) → the island keeps the text with Copy until it is copied, closed or the next take starts;
//   • never into Blurt's own island / panels. Our own windows (the test pad) get a real paste: action, no keystroke;
//   • never into an app other than the one the take started in (`appChanged`): copied instead.
// While pastes overlap (a reformat right after a dictation), one snapshot of the user's clipboard is held: only the
// last paste to finish puts it back, so it is never replaced by dictated text. Test builds use a private pasteboard
// (BLURT_TEST_PASTEBOARD, else one of their own): a test never touches the user's clipboard.
import AppKit
import ApplicationServices
import BlurtCore
import Carbon.HIToolbox
import WebKit

enum DictationInsert {
    /// `held`: neither typed nor copied (a password field had the focus): the text is in the history and the island
    /// offers Copy
    enum Result: String { case pasted, copied, held, none }

    /// A snapshot of the general pasteboard: each item's types and data.
    struct Saved {
        let items: [[(NSPasteboard.PasteboardType, Data)]]
        let changeCount: Int

        static func take(_ pb: NSPasteboard = DictationInsert.pasteboard) -> Saved {
            let items = (pb.pasteboardItems ?? []).map { it in it.types.compactMap { t in it.data(forType: t).map { (t, $0) } } }
            return Saved(items: items, changeCount: pb.changeCount)
        }

        func restore(_ pb: NSPasteboard = DictationInsert.pasteboard) {
            pb.clearContents()
            let objs: [NSPasteboardItem] = items.compactMap { pairs in
                guard !pairs.isEmpty else { return nil }
                let it = NSPasteboardItem()
                for (t, d) in pairs { it.setData(d, forType: t) }
                return it
            }
            if !objs.isEmpty { pb.writeObjects(objs) }
        }
    }

    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Test builds (BLURT_TEST_COMMANDS=1) never type into another app: a test app launched from a terminal inherits
    /// that terminal's Accessibility grant, so the checks below would pass and ⌘V would land in whatever is in front.
    /// Test mode: the test command channel is on, or this isn't the real app's bundle (a renamed test bundle, a bare
    /// `swift build` binary). Either way: no CGEvent is ever posted and no real event tap is installed.
    static var testMode: Bool {
        ProcessInfo.processInfo.environment["BLURT_TEST_COMMANDS"] == "1" || Bundle.main.bundleIdentifier != productionBundleID
    }
    static let productionBundleID = "dev.blurt.recorder"

    /// The clipboard dictation pastes through: the general one; a test build's own (BLURT_TEST_PASTEBOARD names it,
    /// else one for this process), never the user's.
    static let pasteboard: NSPasteboard = {
        guard testMode else { return .general }
        let name = ProcessInfo.processInfo.environment["BLURT_TEST_PASTEBOARD"].flatMap { $0.isEmpty ? nil : $0 }
            ?? "dev.blurt.test.dictation.\(ProcessInfo.processInfo.processIdentifier)"
        return NSPasteboard(name: NSPasteboard.Name(name))
    }()

    /// The user's clipboard while pastes are in flight: taken by the first, put back by the last (`held`).
    private static var held: (saved: Saved, count: Int)?
    private static func hold() {
        if held == nil { held = (Saved.take(), 0) }
        held?.count += 1
    }
    /// A paste finished: the last one puts the clipboard back — unless someone else changed it since (`ours`).
    private static func release(ours: Int) {
        guard var h = held else { return }
        h.count -= 1
        if h.count > 0 { held = h; return }
        held = nil
        if pasteboard.changeCount == ours { h.saved.restore() }
    }

    /// Puts `text` where the user is typing. `appChanged`: the app in front isn't the one the take started in — the
    /// text is copied, never pasted there. `done` gets what happened (on the main queue) — for a paste, once it has
    /// landed (DictationPasteLanding: `field`, read just before as `before`, shows the text), which is when a double
    /// tap's Return may go; the user's clipboard comes back after that, never on a timer that could beat the paste.
    static func insert(_ text: String, appChanged: Bool = false, field: DictationField? = nil,
                       before: (text: String, selection: NSRange)? = nil, done: @escaping (Result) -> Void) {
        guard !text.isEmpty else { return done(.none) }
        lastNoField = testMode && testNoField
        if appChanged {
            copy(text)
            lastCopyReason = "app_changed"
            emit(["event": "dictation_insert", "result": "copied", "why": "app_changed"])
            return done(.copied)
        }
        if testMode {
            // only ever the test pad (our own window, focused or not): a paste: action, no keystroke, no other app
            guard let tv = DictationTestPad.textView else {
                emit(["event": "dictation_insert", "result": "none", "why": "test_mode"])
                return done(.none)
            }
            return paste(text, into: tv, window: tv.window, before: before ?? (tv.string, tv.selectedRange()), done: done)
        }
        let front = NSWorkspace.shared.frontmostApplication
        let me = ProcessInfo.processInfo.processIdentifier
        let trusted = AXIsProcessTrusted()
        // the focused element only says whether the paste is confirmed (and catches a password field); it no longer
        // decides: WeChat's input box and many Electron / web editors aren't an Accessibility text role
        let focus = trusted && front != nil && front?.processIdentifier != me ? focusedElement() : Focus()
        let isText: Bool? = focus.role == nil && focus.pid == nil ? nil : focus.editable && (focus.pid == nil || focus.pid == front?.processIdentifier)
        let decision = DictationPastePolicy.decide(.init(
            hasFrontApp: front != nil, frontIsBlurt: front?.processIdentifier == me, secureInput: IsSecureEventInputEnabled(),
            accessibility: trusted, focusSecure: focus.secure, focusIsText: isText))
        lastNoField = isText == false
        switch decision {
        case .own:
            return insertHere(text, done: done)
        case .copy(let why):
            copy(text)
            lastCopyReason = why
            emit(["event": "dictation_insert", "result": "copied", "why": why, "role": focus.role ?? ""])
            return done(.copied)
        case .hold(let why):
            // a password field: not typed, not copied — copying is the user's call (the island's Copy)
            lastCopyReason = why
            emit(["event": "dictation_insert", "result": "held", "why": why])
            return done(.held)
        case .paste(let confirmed):
            lastPasteConfirmed = confirmed
            hold()
            put(text, transient: true)
            let ours = pasteboard.changeCount
            postCommandV()
            lastPasted = (CACurrentMediaTime(), front?.bundleIdentifier)
            emit(["event": "dictation_insert", "result": "pasted", "app": front?.bundleIdentifier ?? "", "role": focus.role ?? "",
                  "confirmed": confirmed, "no_field": lastNoField])
            // the dictated text stays in the history (and "Copy again" on the island); the user's clipboard comes back
            // once the paste has landed
            land(text, field: field, before: before, ours: ours, done: done)
        }
    }

    /// After ⌘V: `done(.pasted)` (a double tap's Return) once the field shows the text — read every 30 ms, off the main
    /// thread — or after 0.6 s at the latest; the user's clipboard back 0.15 s after the text was seen, else after
    /// 1.5 s (DictationPasteLanding.returnAfter / restoreAfter).
    private static func land(_ text: String, field: DictationField?, before: (text: String, selection: NSRange)?, ours: Int,
                             done: @escaping (Result) -> Void) {
        let t0 = CACurrentMediaTime()
        var returned = false, released = false
        let giveReturn = { (how: String) in
            guard !returned else { return }
            returned = true
            emit(["event": "dictation_landed", "how": how, "ms": Int((CACurrentMediaTime() - t0) * 1000)])
            done(.pasted)
        }
        let releaseAt = { (seen: Double?) in
            guard !released else { return }
            released = true
            let after = DictationPasteLanding.restoreAfter(seen: seen)
            DispatchQueue.main.asyncAfter(deadline: .now() + max(0, t0 + after - CACurrentMediaTime())) { release(ours: ours) }
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + DictationPasteLanding.returnAfter(seen: nil)) {
            giveReturn(field == nil || before == nil ? "unread" : "not_yet")
        }
        guard let f = field, let b = before else { return releaseAt(nil) }
        func check() {
            let read = { f.read()?.text }
            let seen = { (now: String?) -> Bool in
                now.map { DictationPasteLanding.landed(before: b.text, selection: b.selection, now: $0, inserted: text) } ?? false
            }
            let wait = { (now: String?) in
                let t = CACurrentMediaTime() - t0
                if seen(now) { giveReturn("seen"); return releaseAt(t) }
                if t >= DictationPasteLanding.confirmTimeout { return releaseAt(nil) }
                DispatchQueue.main.asyncAfter(deadline: .now() + DictationPasteLanding.poll) { check() }
            }
            // our own text view on the main thread; another app's field through Accessibility off it
            if testMode { return wait(read()) }
            DispatchQueue.global(qos: .userInitiated).async {
                let now = read()
                DispatchQueue.main.async { wait(now) }
            }
        }
        check()
    }

    /// Why the last insert copied instead of pasting (app_changed, secure_input, no_accessibility …).
    static var lastCopyReason: String?

    /// The last ⌘V went to a focus Accessibility recognised as a text field (false: WeChat and the like — the island
    /// then offers "Copy again" in case it didn't land).
    static var lastPasteConfirmed = true
    /// When and into which app the last take was pasted (DictationSendRule: a double tap sends only right after one).
    static var lastPasted: (at: Double, bundle: String?)?

    /// The last ⌘V went to a focus Accessibility could read and it isn't a text field (the desktop, a web page with
    /// nothing focused): the island keeps the text with Copy, and a double tap's Return isn't pressed there.
    static var lastNoField = false
    /// Tests: the test pad's paste counts as one into a focus that isn't a text field (`dictation no-field on`).
    static var testNoField = false

    /// Our own app is in front: a text view in one of our windows gets a paste: (no synthetic key); the island or
    /// anything that isn't a text field gets nothing — the text goes to the clipboard.
    private static func insertHere(_ text: String, done: @escaping (Result) -> Void) {
        // our own web pages (an item's detail, the review page): their edited field gets it, as any app's would (BA-16:
        // dictating into an item's "what happened" only copied) — when the page says an editable element has the focus
        if let w = NSApp.keyWindow, !(w is NSPanel), let web = (w.firstResponder as? NSView).flatMap(webView(around:)) {
            let js = "(function(){var e=document.activeElement;return !!e&&(e.isContentEditable||/^(INPUT|TEXTAREA)$/.test(e.tagName))&&!e.readOnly&&e.type!=='password'})()"
            web.evaluateJavaScript(js) { r, _ in
                guard r as? Bool == true else {
                    copy(text)
                    emit(["event": "dictation_insert", "result": "copied", "why": "own_page_no_field"])
                    return done(.copied)
                }
                hold()
                put(text, transient: true)
                let ours = pasteboard.changeCount
                NSApp.sendAction(#selector(NSText.paste(_:)), to: nil, from: nil)
                emit(["event": "dictation_insert", "result": "pasted", "app": "self", "window": w.title])
                land(text, field: nil, before: nil, ours: ours, done: done)
            }
            return
        }
        // panels are the island, the note bubble, cards: never typed into
        guard let w = NSApp.keyWindow, !(w is NSPanel), let tv = w.firstResponder as? NSTextView, tv.isEditable else {
            copy(text)
            emit(["event": "dictation_insert", "result": "copied", "why": "own_window"])
            return done(.copied)
        }
        paste(text, into: tv, window: w, done: done)
    }

    /// The web view a responder is (or is inside).
    private static func webView(around v: NSView) -> WKWebView? {
        var x: NSView? = v
        while let c = x { if let w = c as? WKWebView { return w }; x = c.superview }
        return nil
    }

    /// Our own text view: the same pasteboard round trip, with the paste: action instead of a keystroke.
    private static func paste(_ text: String, into tv: NSTextView, window w: NSWindow?,
                              before: (text: String, selection: NSRange)? = nil, done: @escaping (Result) -> Void) {
        hold()
        let b = before ?? (tv.string, tv.selectedRange())
        put(text, transient: true)
        let ours = pasteboard.changeCount
        // a test build reads its own pasteboard (paste: reads the general one)
        if testMode { _ = tv.readSelection(from: pasteboard, type: .string) } else { tv.paste(nil) }
        emit(["event": "dictation_insert", "result": "pasted", "app": "self", "window": w?.title ?? ""])
        land(text, field: DictationField.of(tv), before: b, ours: ours, done: done)
    }

    static func copy(_ text: String) { put(text, transient: false) }

    /// Copy Text from Screen (ScreenTextCopy): `text` on `pb` as a copy the user made — it stays there, as Bob's does —
    /// and ⌘V into the app in front. Test builds post nothing (false).
    static func pasteKeeping(_ text: String, on pb: NSPasteboard) -> Bool {
        pb.clearContents()
        pb.setString(text, forType: .string)
        guard !testMode else { return false }
        postCommandV()
        return true
    }

    /// Reformat-last: `text` in place of `range` of the field the last take went into — the range selected (the
    /// test pad's text view; another app's field through Accessibility, read back to be sure), then the same paste as
    /// a dictation. `done(false)`: the field isn't focused any more or wouldn't take the selection (the caller copies).
    static func replace(_ text: String, in field: DictationField, range: NSRange, done: @escaping (Bool) -> Void) {
        guard field.isFocused(), field.select(range) else {
            emit(["event": "dictation_replace", "result": "refused"])
            return done(false)
        }
        insert(text) { r in
            emit(["event": "dictation_replace", "result": r.rawValue])
            done(r == .pasted)
        }
    }

    private static func put(_ text: String, transient: Bool) {
        let pb = pasteboard
        pb.clearContents()
        let it = NSPasteboardItem()
        it.setString(text, forType: .string)
        if transient {      // clipboard managers: not something the user copied
            it.setData(Data(), forType: DictationInsert.transient)
            it.setData(Data(), forType: DictationInsert.autoGenerated)
        }
        pb.writeObjects([it])
    }

    /// ⌘V as a keyboard would send it (HID level: it goes to the frontmost app's key window).
    private static func postCommandV() {
        guard !testMode else { return }          // belt and braces: a test build never posts an event
        let src = CGEventSource(stateID: .hidSystemState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    // MARK: a double tap: Return

    /// Presses Return in the app in front (a double tap of the dictation key: "send"), when DictationSendPolicy allows
    /// it. Test builds never post an event: they report what would have happened ("would press Return"), with the
    /// simulated Accessibility of the test hooks. `pressed` is also true for that test answer.
    static func pressReturn() -> (pressed: Bool, result: String, why: String?) {
        let front = NSWorkspace.shared.frontmostApplication
        let me = ProcessInfo.processInfo.processIdentifier
        let d = DictationSendPolicy.decide(hasFrontApp: front != nil, frontIsBlurt: front?.processIdentifier == me,
                                           secureInput: IsSecureEventInputEnabled(),
                                           accessibility: testMode ? DictationKeys.accessibility : AXIsProcessTrusted())
        if case .skip(let why) = d { return (false, "skipped", why) }
        if testMode {
            emit(["event": "dictation_test_send", "log": "would press Return", "app": front?.bundleIdentifier ?? ""])
            return (true, "would_press_return", nil)
        }
        postReturn()
        return (true, "pressed", nil)
    }

    /// Return as a keyboard would send it, no modifiers (the dictation key is up by now).
    private static func postReturn() {
        guard !testMode else { return }          // belt and braces: a test build never posts an event
        let src = CGEventSource(stateID: .hidSystemState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_Return), keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_Return), keyDown: false)
        down?.flags = []
        up?.flags = []
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    // MARK: what has the focus (Accessibility)

    struct Focus {
        var role: String?
        /// the process the focused element belongs to
        var pid: pid_t?
        var editable = false
        /// a password field (AXSecureTextField as role or subrole): never pasted into
        var secure = false
        static let text: Set<String> = ["AXTextField", "AXTextArea", "AXComboBox", "AXSearchField"]
    }

    static func focusedElement() -> Focus {
        let sys = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(sys, 0.25)
        var ref: CFTypeRef?
        guard AXUIElementCopyAttributeValue(sys, kAXFocusedUIElementAttribute as CFString, &ref) == .success, let r = ref,
              CFGetTypeID(r) == AXUIElementGetTypeID() else { return Focus() }
        let el = r as! AXUIElement   // swiftlint:disable:this force_cast
        var f = Focus()
        var pid: pid_t = 0
        if AXUIElementGetPid(el, &pid) == .success, pid > 0 { f.pid = pid }
        var role: CFTypeRef?
        if AXUIElementCopyAttributeValue(el, kAXRoleAttribute as CFString, &role) == .success { f.role = role as? String }
        var sub: CFTypeRef?
        let subrole = AXUIElementCopyAttributeValue(el, kAXSubroleAttribute as CFString, &sub) == .success ? sub as? String : nil
        f.secure = f.role == "AXSecureTextField" || subrole == "AXSecureTextField"
        var settable: DarwinBoolean = false
        let canSetValue = AXUIElementIsAttributeSettable(el, kAXValueAttribute as CFString, &settable) == .success && settable.boolValue
        var range: CFTypeRef?
        let hasRange = AXUIElementCopyAttributeValue(el, kAXSelectedTextRangeAttribute as CFString, &range) == .success
        var editableAncestor: CFTypeRef?
        let inEditable = AXUIElementCopyAttributeValue(el, "AXEditableAncestor" as CFString, &editableAncestor) == .success
        f.editable = Focus.text.contains(f.role ?? "") || hasRange || inEditable || (canSetValue && f.role != "AXSlider")
        return f
    }
}
